"""Deterministic landscape shared by the place mesh and generated navigation map."""
import math
STEP=24
HALF=384
N=33
SURFACE=44
def radius(a):
    return 244*(1+.115*math.sin(2*a+.6)+.085*math.sin(3*a-1.1)+.035*math.cos(5*a))
def height(x,z):
    a=math.atan2(z,x); q=math.hypot(x,z)/radius(a)
    ripples=2.5*math.sin(x/52)*math.cos(z/67)+1.5*math.sin((x+z)/31)
    deep=-10*math.exp(-((x+62)**2+(z-35)**2)/7000)
    shoal=9*math.exp(-((x-106)**2+(z+74)**2)/4500)
    if q<.70: return 4+deep+shoal+ripples
    if q<1:
        t=(q-.70)/.30;t=t*t*(3-2*t)
        return (4+deep+shoal+ripples)*(1-t)+45*t
    # Low hills blend into the broad outer meadow.
    t=min(1,(q-1)/.5)
    return 45+9*t+11*math.sin(x/112+.8)**2*math.sin(z/107)**2*t
HEIGHTS=[[height(-HALF+i*STEP,-HALF+j*STEP) for j in range(N)] for i in range(N)]
def floor_at(x,z):
    u=max(0,min(N-1-.00001,(x+HALF)/STEP));v=max(0,min(N-1-.00001,(z+HALF)/STEP))
    i,j=int(u),int(v);a,b=u-i,v-j
    h00,h10,h01,h11=HEIGHTS[i][j],HEIGHTS[i+1][j],HEIGHTS[i][j+1],HEIGHTS[i+1][j+1]
    return h00+a*(h10-h00)+b*(h01-h00) if a+b<=1 else h11+(1-a)*(h01-h11)+(1-b)*(h10-h11)
def write_map(path):
    rows=',\n'.join('{'+','.join(f'{h:.6f}' for h in row)+'}' for row in HEIGHTS)
    path.write_text('''-- Generated by tools/landscape.py; terrain triangles use this exact height grid.
local M={Step=24,Half=384,N=33}
local heights={\n'''+rows+'''}
function M.radius(angle)
 return 244*(1+.115*math.sin(2*angle+.6)+.085*math.sin(3*angle-1.1)+.035*math.cos(5*angle))
end
function M.floorHeight(x,z)
 local u=math.clamp((x+M.Half)/M.Step,0,M.N-1-.00001)
 local v=math.clamp((z+M.Half)/M.Step,0,M.N-1-.00001)
 local i,j=math.floor(u)+1,math.floor(v)+1
 local a,b=u-math.floor(u),v-math.floor(v)
 local h00,h10,h01,h11=heights[i][j],heights[i+1][j],heights[i][j+1],heights[i+1][j+1]
 if a+b<=1 then return h00+a*(h10-h00)+b*(h01-h00) end
 return h11+(1-a)*(h01-h11)+(1-b)*(h10-h11)
end
return M
''')
